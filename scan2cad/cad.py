"""Rebuild a scan as an editable, parametric CadQuery model (plus STEP export).

Honest scope: this recognises "machined" shapes - a box / cylinder / sphere body with
round holes and posts. It accepts a feature only if it improves the volume match with the
scan. If the result is a poor match (organic shapes) it falls back to a faceted STEP,
which is a solid but not feature-editable.
"""
from __future__ import annotations

import json
import runpy
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import trimesh

from .primitives import Segmentation


@dataclass
class CadResult:
    mode: str  # "parametric" or "faceted"
    iou: float  # volume overlap of the CAD model with the scan (1.0 = identical)
    base: dict | None
    features: list[dict]
    step_path: str | None
    script_path: str | None
    notes: list[str]


# ---------- analytic occupancy (in the local, box-aligned frame) ----------
def _unit(v):
    v = np.asarray(v, float)
    return v / np.linalg.norm(v)


def _inside_base(p, base):
    if base["type"] == "box":
        return np.all(np.abs(p) <= np.array(base["size"]) / 2, axis=1)
    if base["type"] == "sphere":
        return np.linalg.norm(p, axis=1) <= base["radius"]
    a = _unit(base["axis"])
    t = p @ a
    rad = np.linalg.norm(p - t[:, None] * a, axis=1)
    return (rad <= base["radius"]) & (np.abs(t) <= base["length"] / 2)


def _inside_cyl(p, f):
    a = _unit(f["axis"])
    d = p - np.asarray(f["center"])
    t = d @ a
    rad = np.linalg.norm(d - t[:, None] * a, axis=1)
    return (rad <= f["radius"]) & (t >= f["start"]) & (t <= f["end"])


def _support(base, a):
    """Largest coordinate of the base along unit direction a."""
    if base["type"] == "box":
        return float(np.sum(np.abs(a) * np.array(base["size"]) / 2))
    if base["type"] == "sphere":
        return base["radius"]
    ax = _unit(base["axis"])
    c = abs(float(a @ ax))
    return base["length"] / 2 * c + base["radius"] * np.sqrt(max(0.0, 1 - c * c))


def _iou(a, b):
    u = np.count_nonzero(a | b)
    return np.count_nonzero(a & b) / u if u else 0.0


def _script(base, features, transform):
    return f'''"""Editable parametric model generated by scan2cad.

Change any number below and run `python model.py` to rebuild model.step.
Units: millimetres. Coordinates are in the object's own box-aligned frame (origin at centre).
SCAN_FROM_MODEL maps this frame back to the original scan (4x4, row-major).
"""
import cadquery as cq

BASE = {json.dumps(base)}

# kind: "hole" cuts material, "boss" adds a post. center is a point on the axis;
# start/end are positions along the axis measured from the origin.
FEATURES = {json.dumps(features, indent=2)}

SCAN_FROM_MODEL = {json.dumps(np.asarray(transform).round(6).tolist())}


def V(v):
    return cq.Vector(*v)


def cylinder(radius, start, end, center, axis):
    a = V(axis).normalized()
    c = V(center)
    p0 = c + a * (start - c.dot(a))
    return cq.Solid.makeCylinder(radius, end - start, p0, a)


def build():
    if BASE["type"] == "box":
        sx, sy, sz = BASE["size"]
        body = cq.Solid.makeBox(sx, sy, sz, cq.Vector(-sx / 2, -sy / 2, -sz / 2))
    elif BASE["type"] == "sphere":
        body = cq.Solid.makeSphere(BASE["radius"], cq.Vector(0, 0, 0), cq.Vector(0, 0, 1), -90, 90, 360)
    else:
        a = V(BASE["axis"]).normalized()
        body = cq.Solid.makeCylinder(BASE["radius"], BASE["length"], a * (-BASE["length"] / 2), a)
    for f in FEATURES:
        tool = cylinder(f["radius"], f["start"], f["end"], f["center"], f["axis"])
        body = body.cut(tool) if f["kind"] == "hole" else body.fuse(tool)
    return body.clean()


result = build()

if __name__ == "__main__":
    cq.exporters.export(cq.Workplane().add(result), "model.step")
    print("wrote model.step, volume %.1f mm^3" % result.Volume())
'''


def mesh_to_step(mesh: trimesh.Trimesh, path: str, max_faces: int = 20000) -> list[str]:
    """Faceted STEP solid: exact copy of the scan, but not feature-editable."""
    import cadquery as cq

    notes = []
    if len(mesh.faces) > max_faces:
        mesh = mesh.simplify_quadric_decimation(face_count=max_faces)
        notes.append(f"decimated to {max_faces} faces for STEP export")
    faces = [
        cq.Face.makeFromWires(cq.Wire.makePolygon([cq.Vector(*v) for v in tri], close=True))
        for tri in mesh.triangles
    ]
    solid = cq.Solid.makeSolid(cq.Shell.makeShell(faces))
    cq.exporters.export(cq.Workplane().add(solid), path)
    return notes


def reverse_engineer(mesh: trimesh.Trimesh, seg: Segmentation, out_dir: str,
                     min_iou: float = 0.9, n_samples: int = 20000, seed: int = 0) -> CadResult:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    step, script = out / "model.step", out / "model.py"
    notes: list[str] = []

    def faceted(why):
        notes.append(why)
        notes.extend(mesh_to_step(mesh, str(step)))
        return CadResult("faceted", 0.0, None, [], str(step), None, notes)

    if not mesh.is_watertight:
        return faceted("scan is not watertight, cannot verify a parametric fit")

    # Try the full bounding box, and one fitted with posts/bosses excluded (a post would
    # otherwise inflate the body). Keep whichever frame explains the scan best.
    frames = [mesh.bounding_box_oriented]
    drop = np.zeros(len(mesh.vertices), bool)
    mid = mesh.centroid
    for c in seg.cylinders:
        if not c.convex or c.area >= 0.4 * mesh.area:
            continue
        d = mesh.vertices - c.point
        t = mesh.vertices @ c.axis
        radial = np.linalg.norm(d - (d @ c.axis)[:, None] * c.axis, axis=1)
        eps = 0.02 * (c.t1 - c.t0)
        outward_is_up = abs(c.t1 - mid @ c.axis) > abs(c.t0 - mid @ c.axis)
        beyond = (t > c.t0 + eps) if outward_is_up else (t < c.t1 - eps)
        drop |= (radial <= c.radius * 1.01) & beyond & (t >= c.t0 - eps) & (t <= c.t1 + eps)
    if drop.any() and (~drop).sum() >= 8:
        frames.append(trimesh.PointCloud(mesh.vertices[~drop]).bounding_box_oriented)

    rng = np.random.default_rng(seed)
    best = None
    for obb in frames:
        T = np.asarray(obb.primitive.transform)
        R, centre, ext = T[:3, :3], T[:3, 3], np.asarray(obb.primitive.extents, float)
        local_v = (mesh.vertices - centre) @ R
        lo, hi = local_v.min(0), local_v.max(0)
        pad = 0.02 * (hi - lo)
        pts = lo - pad + rng.random((n_samples, 3)) * (hi - lo + 2 * pad)
        truth = mesh.contains(pts @ R.T + centre)

        cands = [{"type": "box", "size": ext.tolist()},
                 {"type": "sphere", "radius": float(ext.mean() / 2)}]
        for k in range(3):
            o = [i for i in range(3) if i != k]
            ax = np.zeros(3)
            ax[k] = 1
            cands.append({"type": "cylinder", "axis": ax.tolist(), "radius": float(ext[o].mean() / 2),
                          "length": float(ext[k])})
        iou0, bi = max((_iou(_inside_base(pts, c), truth), i) for i, c in enumerate(cands))
        base, occ, best_iou = cands[bi], _inside_base(pts, cands[bi]), iou0

        features: list[dict] = []
        for cyl in seg.cylinders[:32]:
            a = R.T @ cyl.axis
            p = R.T @ (cyl.point - centre)
            p = p - (p @ a) * a
            t_off = float(centre @ cyl.axis)  # t was measured in scan frame; shift to local
            f = {"kind": "boss" if cyl.convex else "hole", "center": p.round(4).tolist(),
                 "axis": a.round(6).tolist(), "radius": round(cyl.radius, 4),
                 "start": round(cyl.t0 - t_off, 4), "end": round(cyl.t1 - t_off, 4)}
            tol = 0.01 * float(ext.max())
            for key, sgn in (("start", -1), ("end", 1)):  # overshoot where a hole meets the outer surface
                if f["kind"] == "hole" and abs(f[key] - sgn * _support(base, sgn * _unit(a))) < tol:
                    f[key] = round(f[key] + sgn * 0.05 * float(ext.max()), 4)
            cy = _inside_cyl(pts, f)
            trial = (occ & ~cy) if f["kind"] == "hole" else (occ | cy)
            new_iou = _iou(trial, truth)
            if new_iou > best_iou + 1e-3:
                best_iou, occ = new_iou, trial
                features.append(f)
        if best is None or best_iou > best[0]:
            best = (best_iou, base, features, T)
    best_iou, base, features, T = best

    if best_iou < min_iou:
        return faceted(f"parametric fit too loose (IoU {best_iou:.2f} < {min_iou}); organic shape")

    script.write_text(_script(base, features, T))
    solid = runpy.run_path(str(script))["result"]
    import cadquery as cq
    cq.exporters.export(cq.Workplane().add(solid), str(step))
    vol_err = abs(solid.Volume() - mesh.volume) / mesh.volume
    notes.append(f"CAD volume differs from scan by {vol_err:.1%}")
    return CadResult("parametric", float(best_iou), base, features, str(step), str(script), notes)
